#!/bin/sh
# Builds the corpus of the benchmark. Usage: benchmark/build.sh [COUNT]
# Draws programs from benchmark/gen.py by increasing seed and keeps COUNT of
# them, 300 by default. A program is kept when g++ -std=c++17 -pedantic-errors
# compiles it, its build with -fsanitize=undefined,address runs without a
# report, and corecpp runs it within its fuel. The sanitizers stand as the
# independent witness that the program has no undefined behaviour. Each kept
# program records its seed and the exit code of g++.
cd "$(dirname "$0")/.."
count=${1:-300}
out=benchmark/corpus
rm -rf "$out"; mkdir -p "$out"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
seed=0; kept=0
while [ "$kept" -lt "$count" ]; do
  seed=$((seed + 1))
  python3 -I benchmark/gen.py "$seed" > "$tmp/p.cpp"
  g++ -std=c++17 -pedantic-errors -fsanitize=undefined,address -fno-sanitize-recover=all \
    -o "$tmp/p" "$tmp/p.cpp" 2>/dev/null || { echo "seed $seed: g++ rejects" >&2; continue; }
  ASAN_OPTIONS=detect_leaks=0 "$tmp/p" >/dev/null 2>"$tmp/err"; code=$?
  if [ -s "$tmp/err" ]; then echo "seed $seed: sanitizer report" >&2; continue; fi
  if bin/corecpp run "$tmp/p.cpp" 2>&1 | grep -q "deeper than the fuel"; then
    echo "seed $seed: out of fuel" >&2; continue
  fi
  name=$(printf 'b%03d' "$kept")
  { echo "// Core C++ benchmark, program $name, generated by benchmark/gen.py from seed $seed."
    echo "// Exit code $code under g++ -std=c++17."
    cat "$tmp/p.cpp"; } > "$out/$name.cpp"
  kept=$((kept + 1))
done
echo "kept $kept programs from $seed seeds"
